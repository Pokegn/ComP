#define ordered_set tree<ll, null_type,less<ll>, rb_tree_tag,tree_order_statistics_node_update>

void solve(){
    ll n,k; cin >> n >> k;
    ll rem = n;
    ll curr = 1;
    ordered_set os;
    for(ll i = 1; i<=n; i++) os.insert(i);
    while(rem > 0){
        ll idx = os.order_of_key(curr);
        idx = (idx + k)%rem;
        curr = *os.find_by_order(idx);
        cout << curr << ' ';
        os.erase(curr);
        rem--;
    }
}


